--[[
                       Short Description
                       -----------------
For this feature, we want to add the following capabilities:
1. Color selection -> white, red, green, blue, yellow, orange, purple, black
2. Line thickness selection -> thickness of 1 through 9
3. Introduction of rectangle tool
4. Different tools have different cursors
5. Rectangle tool can either have no fill or a color fill of choice. Line and fill color of rectangle can vary from one another.
6. When user clicks on '?', Readout Plugin is used to show valid keys
7. All changes can be properly serialized
8. Can still read from version 0.1 files

                           Features
                           --------
- [X] Add capability to draw rectangles
- [X] Different tools have different cursors
- [X] Can cycle through colors via 'c' key
- [X] Can fill backgrounds of rectangles via 'f' key
- [ ] Can change line thickness with 1-9
- [ ] Can serialize as version 0.2
- [ ] Can read version 0.2
- [ ] Can read version 0.1
- [ ] Implement '?' to trigger help readout

--]]


